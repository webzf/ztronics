    def self.editorial_collection_document?(
      document
    )

      data =
        document.data || {}

      return true if
        data["internal_links"] == true

      EDITORIAL_LAYOUTS.include?(
        data["layout"].to_s
      )
    end

    # ========================================================================
    # SCORING HELPERS
    # ========================================================================

    def self.shared_values_score(
      a,
      b,
      points
    )

      (a & b).length *
        points
    end

    def self.token_similarity(
      tokens_a,
      tokens_b
    )

      return 0 if
        tokens_a.empty? ||
        tokens_b.empty?

      shared =
        tokens_a &
        tokens_b

      return 0 if
        shared.empty?

      [
        shared.length * 2,
        20
      ].min
    end

    # ========================================================================
    # TOKENIZER
    # ========================================================================

    def self.tokenize(
      text
    )

      stopwords = %w[
        the
        and
        or
        for
        with
        this
        that
        from
        into
        using
        use
        used
        are
        is
        to
        of
        a
        an
        in
        on
        our
        your
        how
        what
        can
        will
        be
        tutorial
        guide
        project
        projects
        display
        code
        example
        learn
        common
        popular
        embedded
        electronics
        device
        devices
      ]

      normalize_text(
        text
      )
        .scan(
          /[a-z0-9][a-z0-9_-]{2,}/
        )
        .reject do |word|

          stopwords.include?(
            word
          )

        end
        .uniq
    end

    # ========================================================================
    # NORMALIZATION
    # ========================================================================

    def self.normalize_text(
      value
    )

      value.to_s
        .downcase
        .gsub(
          /[^a-z0-9_\-\s]/,
          " "
        )
        .gsub(
          /\s+/,
          " "
        )
        .strip
    end

    def self.normalize_array(
      value
    )

      Array(value)
        .map do |item|

          normalize_text(
            item
          )

        end
        .reject(&:empty?)
        .uniq
    end

    def self.normalize_ids(
      value
    )

      Array(value)
        .map do |item|

          if item.is_a?(Hash)

            item["id"].to_s.strip

          else

            item.to_s.strip

          end

        end
        .reject(&:empty?)
        .uniq
    end

    def self.normalize_url(
      url
    )

      value =
        url.to_s.strip

      value =
        value.split("#").first

      value =
        value.split("?").first

      value =
        "/" if
        value.empty?

      value =
        "/#{value}" unless
        value.start_with?("/")

      value =
        value.chomp("/")

      return "/" if
        value.empty?

      "#{value}/"
    end

    # ========================================================================
    # COUNT GENERATED LINKS
    # ========================================================================

    def self.count_generated_links(
      content
    )

      content.to_s.scan(
        AUTO_LINK_PATTERN
      ).length
    end

