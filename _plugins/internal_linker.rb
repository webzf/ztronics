      current,
      relations,
      settings
    )

      limit =
        settings[
          "analysis_results_per_page"
        ].to_i

      limit =
        5 if
        limit <= 0

      Jekyll.logger.info(
        "Embedded Nerd:",
        "============================================================"
      )

      Jekyll.logger.info(
        "Embedded Nerd:",
        "Internal Link Analysis V3.6"
      )

      Jekyll.logger.info(
        "Embedded Nerd:",
        "#{current[:type].to_s.upcase}: #{current[:title]}"
      )

      Jekyll.logger.info(
        "Embedded Nerd:",
        "URL: #{current[:url]}"
      )

      if relations.empty?

        Jekyll.logger.info(
          "Embedded Nerd:",
          "No linkable relationships found."
        )

      else

        relations.first(limit).each do |relation|

          anchor =
            relation[:opportunity][:keyword]

          Jekyll.logger.info(
            "Embedded Nerd:",
            "#{relation[:type]} | " \
            "#{relation[:target][:title]} | " \
            "score=#{relation[:score]} | " \
            "anchor=\"#{anchor}\" | " \
            "anchor_quality=#{relation[:anchor_quality]} | " \
            "confidence=#{relation[:confidence].upcase} | " \
            "reason=#{relation[:reason]} | " \
            "#{relation[:target][:url]}"
          )

        end
      end

      Jekyll.logger.info(
        "Embedded Nerd:",
        "============================================================"
      )
    end
  end
